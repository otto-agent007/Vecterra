# Markdown is the output format, so HTML autoescaping is off; the HTML shell escapes the few
# untrusted scalars it interpolates explicitly.
_env = Environment(autoescape=False, undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True)


def _money(v: Any) -> str:
    try:
        return "—" if v is None else "${:,.0f}".format(float(v))
    except (TypeError, ValueError):
        return "—"


def _default_score() -> Dict[str, Any]:
    return {"score": None, "confidence": None, "condition": "unknown", "observations": []}


def build_lead_rationale(parcel: Dict[str, Any], scores: Dict[str, Any], zoning: Dict[str, Any]) -> Dict[str, Any]:
    """Property-only factors; keys are restricted to the firewall whitelist."""
    rationale: Dict[str, Any] = {}
    if parcel.get("estimated_equity") is not None:
        rationale["estimated_equity"] = _money(parcel["estimated_equity"])
    if parcel.get("last_sale_date"):
        try:
            years = (datetime.now(timezone.utc).date() - datetime.fromisoformat(str(parcel["last_sale_date"])).date()).days // 365
            rationale["years_since_last_sale"] = years
        except ValueError:
            pass
    if parcel.get("owner_occupied") is not None:
        rationale["owner_occupied"] = "yes" if parcel["owner_occupied"] else "no"
    if parcel.get("lot_area_sqft"):
        rationale["lot_area_sqft"] = f"{float(parcel['lot_area_sqft']):,.0f}"
    rationale["adu_feasibility"] = zoning.get("feasibility", "unknown")
    overall = (scores.get("overall") or {}).get("score")
    if overall is not None:
        rationale["overall_health_score"] = overall
    flags = [k for k in ("roof", "paint", "structure") if ((scores.get(k) or {}).get("score") or 100) < 60]
    if flags:
        rationale["deferred_maintenance_flags"] = ", ".join(flags)
    # Defensive: never let a non-whitelisted key through.
    return {k: v for k, v in rationale.items() if k in ALLOWED_RATIONALE_KEYS}


_PARCEL_DEFAULTS: Dict[str, Any] = {
    "situs_address": None, "apn": "—", "tax_year": None, "assessed_total_value": None,
    "last_sale_date": None, "last_sale_price": None, "estimated_market_value": None,
    "estimated_equity": None, "equity_confidence": None,
}


def render_markdown(parcel: Dict[str, Any], scores: Dict[str, Any], zoning: Dict[str, Any], rationale: Dict[str, Any]) -> str:
    parcel = {**_PARCEL_DEFAULTS, **parcel}
    full_scores = {k: {**_default_score(), **(scores.get(k) or {})} for k in ("roof", "paint", "structure", "overall")}
    observations: List[str] = []
    for k in ("roof", "paint", "structure"):
        observations.extend(full_scores[k].get("observations") or [])

    tmpl = _env.from_string(_MD_TEMPLATE)
    return tmpl.render(
        address=parcel.get("situs_address") or "Address on file",
        apn=parcel.get("apn", "—"),
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        parcel=parcel,
        scores=full_scores,
        observations=observations,
        zoning=zoning,
        rationale=rationale,
        money=_money,
    )


def render_html(markdown_text: str, *, apn: str, firewall_version: str) -> str:
    body = md.markdown(markdown_text, extensions=["tables", "sane_lists"])
    return _env.from_string(_HTML_SHELL).render(
        body=body, apn=escape(apn), generator_version=GENERATOR_VERSION, firewall_version=escape(firewall_version)
    )


def build_dossier_record(state: Dict[str, Any]) -> Dict[str, Any]:
    """Shape pipeline state into a `dossiers` row."""
    parcel = state["parcel"]
    scores = state.get("vision_scores", {})
    return {
        "parcel_id": parcel["id"],
        "scan_id": (state.get("scan") or {}).get("id"),
        "status": "draft" if state.get("compliance_passed") else "compliance_hold",
        "health_scores": {k: scores.get(k) for k in ("roof", "paint", "structure", "overall")},
        "zoning_analysis": state.get("zoning_analysis", {}),
        "lead_rationale": state.get("lead_rationale", {}),
        "compliance_log": state.get("compliance_log", []),
        "compliance_passed": bool(state.get("compliance_passed")),
        "report_markdown": state.get("final_markdown"),
        "report_html": state.get("final_html"),
        "model_versions": state.get("model_versions", {}),
    }
